import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';

const result = await build({
  entryPoints: ['apps/studio/src/client/main.ts'],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari16', 'chrome110'],
  write: false,
  legalComments: 'none',
});
const runtime = result.outputFiles[0].text;
await writeFile('apps/studio/src/export/generated-runtime.ts', `// Generated by npm run client:bundle.\nexport default ${JSON.stringify(runtime)};\n`);
console.log(`Client runtime: ${Buffer.byteLength(runtime)} bytes`);
